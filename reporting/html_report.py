def fig_to_base64_img(fig, alt: str = "") -> str:
    """Renders a matplotlib figure to a base64-encoded inline <img> tag and
    closes the figure. No temp files, no static-asset directory to serve --
    the whole report is one self-contained HTML string."""
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=140, bbox_inches="tight")
    plt.close(fig)
    buf.seek(0)
    encoded = base64.b64encode(buf.read()).decode("ascii")
    return f'<img src="data:image/png;base64,{encoded}" alt="{alt}" />'


def df_to_html_table(df: pd.DataFrame, round_digits: int = 4) -> str:
    display_df = df.copy()
    for col in display_df.select_dtypes(include="number").columns:
        display_df[col] = display_df[col].round(round_digits)
    return display_df.to_html(index=False, border=0, escape=True)


def kpi_html(label: str, value: str) -> str:
    return f'<div class="kpi"><div class="value">{value}</div><div class="label">{label}</div></div>'


def kpi_row_html(*kpis: str) -> str:
    return f'<div class="kpi-row">{"".join(kpis)}</div>'


def note_html(text: str) -> str:
    return f'<div class="note">{text}</div>'


def render_report(title: str, subtitle: str, body_html: str) -> str:
    # Security note: title/subtitle are HTML-escaped here even though most
    # callers pass static, hard-coded strings, because at least one caller
    # (build_explainability_report_html's subtitle="Applicant: {id}") embeds
    # a value that traces back to a request body field
    # (CreditApplicationRequest.customer_id). Without escaping, a
    # customer_id containing a script tag would be reflected verbatim into
    # this HTML report and executed in the browser of whoever opens it
    # (reflected XSS). body_html is intentionally NOT escaped here -- it is
    # assembled by each report generator from a fixed template plus
    # already-escaped table data (df_to_html_table uses to_html(escape=True)),
    # so double-escaping it here would corrupt the markup.
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    safe_title = html.escape(title)
    safe_subtitle = html.escape(subtitle)
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>{safe_title}</title>
{_CSS}
</head>
<body>
  <div class="report">
    <h1>{safe_title}</h1>
    <div class="subtitle">{safe_subtitle}</div>
    {body_html}
    <footer>Generated by Credit Risk Intelligence Platform &middot; {generated_at}</footer>
  </div>
</body>
</html>"""
